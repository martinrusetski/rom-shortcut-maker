import Foundation
import Darwin

/// Shared destination allocation and ownership checks for preview, creation,
/// replacement, and cleanup. A title alone never establishes ownership.
enum GameBundleDestination {
    static let gameKey = "RomShortcutMakerGameKey"

    static func pathKey(_ url: URL) -> String {
        url.standardizedFileURL.path.precomposedStringWithCanonicalMapping
            .folding(options: .caseInsensitive, locale: Locale(identifier: "en_US_POSIX"))
    }

    static func names(
        for games: [GameEntry], previousState: GameConversionState?, outputDirectory: URL?
    ) -> [String: String] {
        let previous = previousState?.convertedGames ?? []
        var reserved: [String: Set<String>] = [:]
        func nameKey(_ name: String) -> String {
            pathKey(URL(fileURLWithPath: "/").appendingPathComponent(name))
        }
        if let outputDirectory {
            for record in previous {
                let url = URL(fileURLWithPath: record.bundlePath)
                if pathKey(url.deletingLastPathComponent()) == pathKey(outputDirectory) {
                    reserved[nameKey(url.deletingPathExtension().lastPathComponent), default: []]
                        .insert(record.stableKey)
                }
            }
            // Reserve unrelated existing apps too. The installer rechecks
            // ownership at commit time in case the destination changes later.
            for url in (try? FileManager.default.contentsOfDirectory(
                at: outputDirectory, includingPropertiesForKeys: nil)) ?? []
                where url.pathExtension.lowercased() == "app" {
                let key = nameKey(url.deletingPathExtension().lastPathComponent)
                if reserved[key] == nil {
                    reserved[key] = [metadata(at: url)?[gameKey] as? String ?? "existing-file"]
                }
            }
        }
        let bases = Dictionary(grouping: games) {
            nameKey(DefaultAppBundleGenerator.sanitizedBundleName($0.title))
        }
        var result: [String: String] = [:]
        for game in games.sorted(by: { $0.stableKey < $1.stableKey }) {
            let base = DefaultAppBundleGenerator.sanitizedBundleName(game.title)
            let prior = previous.first { $0.stableKey == game.stableKey && $0.title == game.title }
            let priorName = prior.map { URL(fileURLWithPath: $0.bundlePath).deletingPathExtension().lastPathComponent }
            var name = priorName ?? base
            let hasPriorClaim = reserved[nameKey(name)] == [game.stableKey]
            if (!hasPriorClaim && priorName == nil && (bases[nameKey(base)]?.count ?? 0) > 1)
                || !(reserved[nameKey(name)] ?? []).subtracting([game.stableKey]).isEmpty {
                name = base + " (" + String(game.stableKey.prefix(8)) + ")"
            }
            var suffix = 2
            let disambiguated = name
            while !(reserved[nameKey(name)] ?? []).subtracting([game.stableKey]).isEmpty {
                name = disambiguated + " (\(suffix))"
                suffix += 1
            }
            reserved[nameKey(name), default: []].insert(game.stableKey)
            result[game.stableKey] = name
        }
        return result
    }

    private static func metadata(at url: URL) -> [String: Any]? {
        guard let values = try? url.resourceValues(forKeys: [.isSymbolicLinkKey, .isDirectoryKey]),
              values.isSymbolicLink != true, values.isDirectory == true,
              let data = try? Data(contentsOf: url.appendingPathComponent("Contents/Info.plist")),
              let plist = try? PropertyListSerialization.propertyList(from: data, format: nil) as? [String: Any]
        else { return nil }
        return plist
    }

    static func isOwned(_ url: URL, by stableKey: String, recordedPath: String?) -> Bool {
        guard let plist = metadata(at: url) else { return false }
        if let owner = plist[gameKey] as? String { return owner == stableKey }
        // Existing launchers predate the ownership key. Only adopt a recorded
        // path that still has our executable, identifier, and script marker.
        guard let recordedPath, pathKey(url) == pathKey(URL(fileURLWithPath: recordedPath)),
              (plist["CFBundleIdentifier"] as? String)?.hasPrefix("com.romshortcutmaker.") == true,
              plist["CFBundleExecutable"] as? String == "launch.sh",
              let script = try? String(contentsOf: url.appendingPathComponent("Contents/MacOS/launch.sh"), encoding: .utf8)
        else { return false }
        return script.contains("# Generated by Rom Shortcut Maker\n")
    }

    /// Both paths are on the output volume. An exchange leaves the old app at
    /// the staging path until the caller cleans it up; a failed rename leaves
    /// the destination intact. Never fall back to deleting the destination.
    static func commit(staged: URL, destination: URL, replacing: Bool) throws {
        let flags = replacing ? UInt32(RENAME_SWAP) : UInt32(RENAME_EXCL)
        guard renameatx_np(AT_FDCWD, staged.path, AT_FDCWD, destination.path, flags) == 0 else {
            throw NSError(domain: NSPOSIXErrorDomain, code: Int(errno), userInfo: [
                NSFilePathErrorKey: destination.path
            ])
        }
    }
}
